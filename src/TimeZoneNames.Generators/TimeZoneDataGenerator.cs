using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace TimeZoneNames.Generators;

/// <summary>
/// Encodes data.json into the byte array that TimeZoneData.Load() decodes, in the order Load() reads it.
/// A byte array initializer compiles to a data blob rather than to IL, so the JIT has nothing large to compile.
/// </summary>
[Generator]
public class TimeZoneDataGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var source = context.AdditionalTextsProvider
            .Where(file => Path.GetFileName(file.Path) == "data.json")
            .Select((file, ct) => Generate(file.GetText(ct)!.ToString()));

        context.RegisterSourceOutput(source, (spc, code) => spc.AddSource("TimeZoneData.g.cs", SourceText.From(code, Encoding.UTF8)));
    }

    private static string Generate(string json)
    {
        using var reader = new JsonTextReader(new StringReader(json)) { DateParseHandling = DateParseHandling.None };
        var data = JObject.Load(reader);
        var writer = new Writer();

        writer.Dictionary(data["TzdbZoneCountries"], writer.Array);
        writer.Dictionary(data["CldrZoneCountries"], writer.Array);
        writer.Dictionary(data["CldrMetazones"], writer.String);
        writer.Dictionary(data["CldrPrimaryZones"], writer.String);
        writer.Dictionary(data["CldrAliases"], writer.String);
        writer.Dictionary(data["CldrLanguageData"], language =>
        {
            writer.NullableValues(language["Formats"]);
            writer.String(language["FallbackFormat"]);
            writer.Dictionary(language["ShortNames"], writer.Values);
            writer.Dictionary(language["LongNames"], writer.Values);
            writer.Dictionary(language["CountryNames"], writer.String);
            writer.Dictionary(language["CityNames"], writer.String);
        });

        var zones = (JArray)data["SelectionZones"]!;
        writer.Int(zones.Count);
        foreach (var zone in zones)
        {
            writer.String(zone["Id"]);
            writer.Int(DateTime.Parse((string)zone["ThresholdUtc"]!, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind).Ticks);
        }

        writer.Dictionary(data["DisplayNames"], names => writer.Dictionary(names, writer.String));

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("namespace TimeZoneNames;");
        sb.AppendLine();
        sb.AppendLine("internal partial class TimeZoneData");
        sb.AppendLine("{");
        sb.Append("    private static byte[] Blob() => new byte[] { ");
        foreach (var b in writer.ToArray())
        {
            sb.Append(b).Append(',');
        }
        sb.AppendLine(" };");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Writes each string as an index into a pool of distinct strings, so Load() creates every string once.
    /// </summary>
    private sealed class Writer
    {
        private readonly MemoryStream _body = new();
        private readonly Dictionary<string, int> _ids = new(StringComparer.Ordinal);
        private readonly List<string> _pool = new();

        public void Int(long value) => Int(_body, value);

        public void String(JToken? token)
        {
            if (token is not { Type: JTokenType.String })
            {
                Int(0);
                return;
            }

            var value = (string)token!;
            if (!_ids.TryGetValue(value, out var id))
            {
                _pool.Add(value);
                id = _pool.Count;
                _ids.Add(value, id);
            }

            Int(id);
        }

        public void Array(JToken token)
        {
            var array = (JArray)token;
            Int(array.Count);
            foreach (var item in array)
            {
                String(item);
            }
        }

        public void Dictionary(JToken? token, Action<JToken> value)
        {
            var properties = ((JObject)token!).Properties().ToList();
            Int(properties.Count);
            foreach (var property in properties)
            {
                String(property.Name);
                value(property.Value);
            }
        }

        public void Values(JToken token)
        {
            String(token["Generic"]);
            String(token["Standard"]);
            String(token["Daylight"]);
        }

        public void NullableValues(JToken? token)
        {
            if (token is not JObject values)
            {
                Int(0);
                return;
            }

            Int(1);
            Values(values);
        }

        public byte[] ToArray()
        {
            var output = new MemoryStream();
            Int(output, _pool.Count);
            foreach (var value in _pool)
            {
                var bytes = Encoding.UTF8.GetBytes(value);
                Int(output, bytes.Length);
                output.Write(bytes, 0, bytes.Length);
            }

            _body.WriteTo(output);
            return output.ToArray();
        }

        private static void Int(Stream stream, long value)
        {
            while (value >= 0x80)
            {
                stream.WriteByte((byte)(value | 0x80));
                value >>= 7;
            }

            stream.WriteByte((byte)value);
        }
    }
}
